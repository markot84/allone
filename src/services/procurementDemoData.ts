function makeItems(sheetType: string, rows: Record<string, string>[]): { id: string; data: Record<string, unknown> }[] {
  const ts = Date.now();
  return rows.map((row, idx) => ({
    id: `demo_${sheetType}_${idx}_${ts}`,
    data: { ...row, rowIndex: idx, sheetType },
  }));
}


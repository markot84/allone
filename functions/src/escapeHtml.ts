// HTML-escape member-controlled strings before interpolating into outbound email HTML.
// `&` is replaced first so the other entities aren't double-encoded.
export function escapeHtml(s: unknown): string {
  return String(s ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
